#!/usr/bin/env python3
"""Generate and audit the only permitted SplaTAM config deltas for this task."""

from __future__ import annotations

import argparse
import copy
import json
import pprint
from importlib.machinery import SourceFileLoader
from pathlib import Path
from typing import Any


SOURCE_HEAD = "da6bbcd24c248dc884ac7f49d62e91b841b26ccc"
TRAIN_SHA256 = "167066916ce1a3281ac754dfdeec37ada9f5b0e31227c731c94cebb698a2a6e3"


def diff(before: Any, after: Any, path: str = "config") -> dict[str, dict[str, Any]]:
    changes: dict[str, dict[str, Any]] = {}
    if isinstance(before, dict) and isinstance(after, dict):
        for key in sorted(set(before) | set(after)):
            child = f"{path}.{key}"
            if key not in before or key not in after:
                changes[child] = {"before": before.get(key), "after": after.get(key)}
            else:
                changes.update(diff(before[key], after[key], child))
    elif before != after:
        changes[path] = {"before": before, "after": after}
    return changes


def write_python_config(path: Path, config: dict[str, Any]) -> None:
    text = "# Generated by build_splatam_task_configs.py; do not edit after execution lock.\n"
    text += "config = " + pprint.pformat(config, sort_dicts=True, width=120) + "\n"
    path.write_text(text, encoding="utf-8")


def write_dataset_yaml(path: Path, manifest: Path, asset_root: Path, mask: str) -> None:
    path.write_text(
        "\n".join(
            (
                "dataset_name: arkitscenes",
                "scene_id: '48018874'",
                "expected_split: TRAIN",
                f"manifest_path: '{manifest}'",
                f"manifest_sha256: '{TRAIN_SHA256}'",
                f"asset_root: '{asset_root}'",
                f"depth_mask_mode: '{mask}'",
                "",
            )
        ),
        encoding="utf-8",
    )


def resolved(parent: dict[str, Any], args: argparse.Namespace, *, run_name: str, frames: int) -> dict[str, Any]:
    result = copy.deepcopy(parent)
    data = result["data"]
    data.update(
        {
            "dataset_name": "arkitscenes",
            "basedir": str(args.asset_root.parent),
            "sequence": "48018874",
            "gradslam_data_cfg": str(args.config_root / "arkitscenes_train_dataset.yaml"),
            "desired_image_height": 192,
            "desired_image_width": 256,
            "desired_image_height_init": 192,
            "desired_image_width_init": 256,
            "num_frames": frames,
        }
    )
    if frames != 214:
        data["end"] = frames
    result.update(
        {
            "workdir": str(args.output_root),
            "run_name": run_name,
            "seed": 20260730,
            "use_wandb": False,
        }
    )
    return result


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--task-root", type=Path, required=True)
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--asset-root", type=Path, required=True)
    args = parser.parse_args()
    args.source = args.source.resolve()
    args.task_root = args.task_root.resolve()
    args.manifest = args.manifest.resolve()
    args.asset_root = args.asset_root.resolve()
    args.config_root = args.task_root / "config"
    args.output_root = args.task_root / "outputs"
    args.config_root.mkdir(parents=True, exist_ok=True)

    parent_path = args.source / "configs/scannetpp/gaussian_splatting.py"
    parent_module = SourceFileLoader("splatam_official_parent_config", str(parent_path)).load_module()
    parent = copy.deepcopy(parent_module.config)
    if parent["data"]["dataset_name"] != "scannetpp":
        raise RuntimeError("unexpected official parent config")
    if parent["train"]["lrs_mapping"]["cam_unnorm_rots"] != 0.0 or parent["train"]["lrs_mapping"]["cam_trans"] != 0.0:
        raise RuntimeError("camera learning must remain disabled")

    write_dataset_yaml(args.config_root / "arkitscenes_train_dataset.yaml", args.manifest, args.asset_root, "depth_gt_zero")
    smoke = resolved(parent, args, run_name="arkitscenes_48018874_canonical_smoke", frames=20)
    baseline = resolved(parent, args, run_name="arkitscenes_48018874_canonical_baseline", frames=214)
    write_python_config(args.config_root / "splatam_arkitscenes_smoke_config.py", smoke)
    write_python_config(args.config_root / "splatam_arkitscenes_baseline_config.py", baseline)

    smoke_diff = diff(parent, smoke)
    baseline_diff = diff(parent, baseline)
    permitted_common = {
        "config.data.dataset_name",
        "config.data.basedir",
        "config.data.sequence",
        "config.data.gradslam_data_cfg",
        "config.data.desired_image_height",
        "config.data.desired_image_width",
        "config.data.desired_image_height_init",
        "config.data.desired_image_width_init",
        "config.data.end",
        "config.data.num_frames",
        "config.workdir",
        "config.run_name",
        "config.seed",
        "config.use_wandb",
    }
    for name, changes in (("smoke", smoke_diff), ("baseline", baseline_diff)):
        unexpected = sorted(set(changes) - permitted_common)
        if unexpected:
            raise RuntimeError(f"unauthorized {name} config changes: {unexpected}")
    if "config.data.end" in baseline_diff:
        raise RuntimeError("formal baseline must retain the parent dataset end setting")
    evidence = {
        "status": "PASS_AUTHORIZED_SPLATAM_CONFIG_DIFF_ONLY",
        "official_source_head": SOURCE_HEAD,
        "parent_config": "configs/scannetpp/gaussian_splatting.py",
        "train_manifest_sha256": TRAIN_SHA256,
        "allowed_change_categories": [
            "dataset class/path",
            "scene and TRAIN manifest",
            "input resolution and depth scale through adapter",
            "smoke/formal frame count",
            "output/log path",
            "seed 20260730",
            "wandb disabled",
        ],
        "smoke": {"frames": 20, "changes": smoke_diff},
        "baseline": {"frames": 214, "changes": baseline_diff},
        "frozen_parent_semantics_unchanged": {
            "learning_rates": parent["train"]["lrs_mapping"],
            "mapping_iterations": parent["train"]["num_iters_mapping"],
            "loss_weights": parent["train"]["loss_weights"],
            "densification": parent["train"]["densify_dict"],
            "gaussian_distribution": parent["gaussian_distribution"],
            "load_checkpoint": parent["load_checkpoint"],
            "save_checkpoints": parent["save_checkpoints"],
        },
    }
    (args.config_root / "resolved_config_diff.json").write_text(
        json.dumps(evidence, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    print(evidence["status"])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
